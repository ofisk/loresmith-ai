/**
 * UI consistency Phase 0 audit — inventories raw Tailwind color utilities and
 * modal-size usage across src/, per docs/UI_CONSISTENCY_SYSTEM.md.
 *
 * This is a reporting tool, not a CI gate (that's Phase 3's
 * check-design-tokens.mjs). Run manually and regenerate the checked-in
 * report when the inventory needs refreshing.
 *
 * Run: node scripts/check/audit-design-tokens.mjs [--write] [paths...]
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
export const ROOT = path.resolve(__dirname, "../..");
export const REPORT_PATH = path.join(ROOT, "docs", "UI_TOKEN_AUDIT.md");
const DEFAULT_PATHS = ["src"];
const SCANNABLE_RE = /\.(tsx|ts)$/;

/**
 * Tailwind's semantic/brand color families. Deliberately excludes the
 * structural neutrals (neutral, gray, zinc, stone, slate, black, white)
 * since those aren't drift candidates — there's no single "the app's neutral"
 * token to duplicate. Anything in this list *should* eventually route
 * through a design token (--color-primary, a future --color-destructive,
 * etc.) instead of being reached for directly.
 */
export const SEMANTIC_COLOR_FAMILIES = [
	"red",
	"orange",
	"amber",
	"yellow",
	"lime",
	"green",
	"emerald",
	"teal",
	"cyan",
	"sky",
	"blue",
	"indigo",
	"violet",
	"purple",
	"fuchsia",
	"pink",
	"rose",
];

const COLOR_UTILITY_RE = new RegExp(
	`\\b(?:bg|text|border|ring|fill|stroke|from|via|to|decoration|divide|outline|caret|accent)-(${SEMANTIC_COLOR_FAMILIES.join("|")})-(?:50|100|200|300|400|500|600|700|800|900|950)\\b`,
	"g"
);

const MODAL_SIZE_RE = /\bmodal-size-(sm|md|xl|standard|auth)\b/g;

const BUTTON_VARIANT_RE = /<Button\b[^>]*?\bvariant=["']([\w-]+)["']/g;

function walk(dir, out = []) {
	for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
		const full = path.join(dir, entry.name);
		if (entry.isDirectory()) {
			walk(full, out);
		} else if (SCANNABLE_RE.test(entry.name)) {
			out.push(full);
		}
	}
	return out;
}

function lineNumberAt(content, index) {
	let line = 1;
	for (let i = 0; i < index; i++) {
		if (content[i] === "\n") line++;
	}
	return line;
}

function relative(file) {
	return path.relative(ROOT, file).split(path.sep).join("/");
}

/** Scan the given root-relative paths for raw semantic-color Tailwind utilities. */
export function scanRawColorUtilities(paths = DEFAULT_PATHS) {
	const files = paths.flatMap((p) => walk(path.join(ROOT, p)));
	const occurrences = [];
	for (const file of files) {
		const content = fs.readFileSync(file, "utf8");
		for (const match of content.matchAll(COLOR_UTILITY_RE)) {
			occurrences.push({
				file: relative(file),
				line: lineNumberAt(content, match.index),
				family: match[1],
				match: match[0],
			});
		}
	}
	return occurrences;
}

/** Scan for modal-size-* usage, so the "finite set" of sizes is grounded in reality. */
export function scanModalSizeUsage(paths = DEFAULT_PATHS) {
	const files = paths.flatMap((p) => walk(path.join(ROOT, p)));
	const occurrences = [];
	for (const file of files) {
		const content = fs.readFileSync(file, "utf8");
		for (const match of content.matchAll(MODAL_SIZE_RE)) {
			occurrences.push({
				file: relative(file),
				line: lineNumberAt(content, match.index),
				size: match[1],
			});
		}
	}
	return occurrences;
}

/** Scan for <Button variant="..."> usage, to catalog the variants actually in play. */
export function scanButtonVariantUsage(paths = DEFAULT_PATHS) {
	const files = paths.flatMap((p) => walk(path.join(ROOT, p)));
	const occurrences = [];
	for (const file of files) {
		const content = fs.readFileSync(file, "utf8");
		for (const match of content.matchAll(BUTTON_VARIANT_RE)) {
			occurrences.push({
				file: relative(file),
				line: lineNumberAt(content, match.index),
				variant: match[1],
			});
		}
	}
	return occurrences;
}

function groupCount(items, key) {
	const counts = new Map();
	for (const item of items) {
		counts.set(item[key], (counts.get(item[key]) ?? 0) + 1);
	}
	return [...counts.entries()].sort((a, b) => b[1] - a[1]);
}

function fileCount(items) {
	return new Set(items.map((i) => i.file)).size;
}

function renderReport(colorHits, modalHits, buttonHits) {
	const lines = [];
	lines.push("# UI token audit (Phase 0)");
	lines.push("");
	lines.push(
		"Generated by `scripts/check/audit-design-tokens.mjs --write`. Grounds " +
			"[UI_CONSISTENCY_SYSTEM.md](UI_CONSISTENCY_SYSTEM.md)'s Phase 0 in real " +
			"numbers instead of estimates — regenerate after each migration batch " +
			"in Phase 2 to track progress toward zero."
	);
	lines.push("");
	lines.push("## Raw semantic-color Tailwind utilities");
	lines.push("");
	lines.push(
		`${colorHits.length} occurrences across ${fileCount(colorHits)} files, ` +
			"bypassing a design token (`--color-primary`, or a future " +
			"`--color-destructive`/etc.)."
	);
	lines.push("");
	lines.push("| Color family | Occurrences |");
	lines.push("| --- | --- |");
	for (const [family, count] of groupCount(colorHits, "family")) {
		lines.push(`| ${family} | ${count} |`);
	}
	lines.push("");
	lines.push("<details><summary>All occurrences (file:line)</summary>");
	lines.push("");
	for (const hit of colorHits) {
		lines.push(`- \`${hit.file}:${hit.line}\` — \`${hit.match}\``);
	}
	lines.push("");
	lines.push("</details>");
	lines.push("");
	lines.push("## `modal-size-*` usage");
	lines.push("");
	lines.push(
		`${modalHits.length} occurrences across ${fileCount(modalHits)} files.`
	);
	lines.push("");
	lines.push("| Size | Occurrences |");
	lines.push("| --- | --- |");
	for (const [size, count] of groupCount(modalHits, "size")) {
		lines.push(`| ${size} | ${count} |`);
	}
	lines.push("");
	lines.push('## `<Button variant="...">` usage');
	lines.push("");
	lines.push(
		`${buttonHits.length} explicit-variant occurrences across ${fileCount(buttonHits)} files ` +
			"(excludes default-variant usages that omit the prop)."
	);
	lines.push("");
	lines.push("| Variant | Occurrences |");
	lines.push("| --- | --- |");
	for (const [variant, count] of groupCount(buttonHits, "variant")) {
		lines.push(`| ${variant} | ${count} |`);
	}
	lines.push("");
	return lines.join("\n");
}

function main() {
	const args = process.argv.slice(2);
	const write = args.includes("--write");
	const explicitPaths = args.filter((a) => !a.startsWith("--"));
	const paths = explicitPaths.length > 0 ? explicitPaths : DEFAULT_PATHS;

	const colorHits = scanRawColorUtilities(paths);
	const modalHits = scanModalSizeUsage(paths);
	const buttonHits = scanButtonVariantUsage(paths);

	if (write) {
		fs.writeFileSync(
			REPORT_PATH,
			renderReport(colorHits, modalHits, buttonHits)
		);
		console.log(`Wrote ${relative(REPORT_PATH)}`);
		return;
	}

	console.log(
		`Raw semantic-color utilities: ${colorHits.length} (${fileCount(colorHits)} files)`
	);
	for (const [family, count] of groupCount(colorHits, "family")) {
		console.log(`  ${family}: ${count}`);
	}
	console.log(
		`modal-size-* usage: ${modalHits.length} (${fileCount(modalHits)} files)`
	);
	for (const [size, count] of groupCount(modalHits, "size")) {
		console.log(`  ${size}: ${count}`);
	}
	console.log(
		`Button variant usage: ${buttonHits.length} (${fileCount(buttonHits)} files)`
	);
	for (const [variant, count] of groupCount(buttonHits, "variant")) {
		console.log(`  ${variant}: ${count}`);
	}
	console.log("\nRun with --write to regenerate docs/UI_TOKEN_AUDIT.md");
}

if (import.meta.url === `file://${process.argv[1]}`) {
	main();
}
